export type MessageKey = keyof typeof en;

export const tables: Record<Locale, Record<MessageKey, string>> = { en };
let current: Locale = "en";

/** English is the only interface language; the arguments are kept so callers compile. */
export function resolveLocale(_preference?: LocalePreference, _systemLanguage?: string): Locale {
  return "en";
}

export function setLocale(locale: Locale): void {
  current = locale;
}

export function locale(): Locale {
  return current;
}

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  const template = tables[current][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : match,
  );
}
